#!/bin/sh
# Tests this repo's own setup: its agent instructions, docs, project file and
# starter git hooks.

ROOT=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=tests/lib/assert.sh
. "$ROOT/tests/lib/assert.sh"

# --- CLAUDE.md and AGENTS.md

expected_claude="$(tmp_dir)/CLAUDE.md"
printf '@AGENTS.md\n' >"$expected_claude"
assert_file_same "$ROOT/CLAUDE.md" "$expected_claude"

assert_exit 0 test -f "$ROOT/AGENTS.md"
assert_exit 0 test "$(wc -l <"$ROOT/AGENTS.md")" -lt 200
agents=$(cat "$ROOT/AGENTS.md")
assert_contains "$agents" "Closes #"
# A fresh clone has no hooks until someone runs this.
assert_contains "$agents" "git config core.hooksPath .githooks"
# Without this, the superpowers skill's menu conflicts with the Workflow section.
assert_contains "$agents" "landing follows the Workflow section here"
assert_contains "$agents" "no worktree or question just to protect a running dev server"

# --- docs

spec=docs/superpowers/specs/2026-11-05-dev-workflow-methodology-design.md
assert_exit 0 test -f "$ROOT/$spec"
assert_exit 0 test -f "$ROOT/docs/superpowers/plans/2026-11-05-dev-workflow-methodology.md"
assert_contains "$(cat "$ROOT/docs/decisions.md")" "${spec#docs/}"
# It explains the format and records no run until one has happened.
maintenance=$(cat "$ROOT/docs/maintenance.md")
assert_contains "$maintenance" "YYYY-MM-DD"
assert_exit 1 grep -Eq '^- |[0-9]{4}-[0-9]{2}-[0-9]{2}' "$ROOT/docs/maintenance.md"

# --- .claude/dev-workflow.json

assert_exit 0 jq -e '
  .schemaVersion == 1
  and .pluginVersion == "1.0.0"
  and .stack == []
  and .hasScreens == false
  and .commands.check == "scripts/check"
  and .commands.verify == "scripts/verify"
' "$ROOT/.claude/dev-workflow.json"

# --- .githooks

# Git silently skips a hook that isn't executable.
for hook in commit-msg pre-push; do
  assert_exit 0 test -x "$ROOT/.githooks/$hook"
done

# --- .githooks/commit-msg

message_file="$(tmp_dir)/COMMIT_EDITMSG"

commit_msg() { # <message>
  printf '%s\n' "$1" >"$message_file"
  sh "$ROOT/.githooks/commit-msg" "$message_file"
}

# The format: a Conventional Commit whose subject ends with its issue number.
for good in \
  'chore: good (#2)' \
  'feat(scope)!: subject (#12)' \
  'fixup! chore: good (#2)' \
  'squash! chore: good (#2)'; do
  assert_exit 0 commit_msg "$good"
done
for bad in \
  'bad message' \
  'chore: no issue number' \
  'chore: (#2)' \
  'nonsense: unknown type (#2)' \
  "Merge branch 'other' (#2)" \
  ''; do
  assert_exit 1 commit_msg "$bad"
done

# Attribution anywhere in the message, whatever the case.
good_subject='chore: good (#2)'
for attribution in \
  'Co-Authored-By: Claude' \
  'Co-Authored-By: Claude <noreply@anthropic.com>' \
  'co-authored-by: claude code <noreply@anthropic.com>' \
  'Co-Authored-By: Some Model 9 <noreply@anthropic.com>' \
  'Co-authored-by: GitHub Copilot <copilot@example.com>' \
  'Co-authored-by: Codex <noreply@openai.com>' \
  'Generated with Claude Code' \
  'Generated with [Claude Code](https://example.com/claude-code)' \
  "$(printf '\360\237\244\226') Generated with [Claude Code](https://example.com/claude-code)" \
  'Written by Claude'; do
  assert_exit 1 commit_msg "$good_subject

Why this change.

$attribution"
done

# People can be co-authors, even one named like a tool.
for human in \
  'Co-Authored-By: Ana Ruiz <ana@example.com>' \
  'Co-Authored-By: Claude Dupont <claude.dupont@example.com>'; do
  assert_exit 0 commit_msg "$good_subject

$human"
done

# A tool can be what the change is about.
assert_exit 0 commit_msg 'docs: explain how Claude Code loads hooks (#2)'
assert_exit 0 commit_msg "$good_subject

The hook rejects trailers naming Claude, and lines generated with it.
Data generated by the script is unchanged."

# Git passes comments and the diff of `commit -v` to the hook, then removes them.
assert_exit 0 commit_msg "# A comment before the subject

$good_subject

# Co-Authored-By: Claude
# ------------------------ >8 ------------------------
# Do not modify or remove the line above.
diff --git a/notes b/notes
Co-Authored-By: Claude
 Generated with Claude Code"
assert_exit 1 commit_msg '# chore: only a comment (#2)'

# --- .githooks/pre-push, through real pushes to a bare remote

fixture="$(tmp_dir)/a b/repo"
new_repo "$fixture"
remote="$(tmp_dir)/a b/remote.git"
git init -q --bare -b main "$remote"
mkdir -p "$fixture/.githooks" "$fixture/scripts"
cp "$ROOT/.githooks/pre-push" "$fixture/.githooks/"
git -C "$fixture" config core.hooksPath .githooks
git -C "$fixture" remote add origin "$remote"

check_log="$(tmp_dir)/check.log"
export CHECK_LOG="$check_log"
export CHECK_EXIT=0
cat >"$fixture/scripts/check" <<'STUB'
#!/bin/sh
echo ran >>"$CHECK_LOG"
exit "$CHECK_EXIT"
STUB

new_commit() {
  git -C "$fixture" commit -q --allow-empty -m "chore: a commit (#2)"
}

push() { # <git push arguments...>
  git -C "$fixture" push -q origin "$@" 2>&1
}

remote_sha() { # <branch>: prints nothing if the remote doesn't have it.
  git -C "$remote" rev-parse -q --verify "refs/heads/$1"
}

# A new repo's first push may go to main, and it still runs the check.
new_commit
: >"$check_log"
assert_exit 0 push main
assert_exit 0 test "$(remote_sha main)" = "$(git -C "$fixture" rev-parse main)"
assert_contains "$(cat "$check_log")" "ran"

# After that, a direct push to main is rejected before the check runs.
main_on_remote=$(remote_sha main)
new_commit
: >"$check_log"
assert_exit 1 push main
assert_contains "$(push main)" "directly to main"
assert_exit 0 test "$(remote_sha main)" = "$main_on_remote"
assert_exit 0 test ! -s "$check_log"

# Going through another local branch name doesn't get around it.
git -C "$fixture" switch -q -c chore/2-thing
assert_exit 1 push chore/2-thing:main
assert_exit 0 test "$(remote_sha main)" = "$main_on_remote"

# Neither does deleting it.
assert_exit 1 push :main
assert_contains "$(push :main)" "directly to main"
assert_exit 0 test "$(remote_sha main)" = "$main_on_remote"

# One forbidden ref rejects the whole push.
assert_exit 1 push chore/2-thing main
assert_exit 1 test -n "$(remote_sha chore/2-thing)"

# Other branches push when the check passes.
: >"$check_log"
assert_exit 0 push chore/2-thing
assert_exit 0 test "$(remote_sha chore/2-thing)" = "$(git -C "$fixture" rev-parse chore/2-thing)"
assert_contains "$(cat "$check_log")" "ran"

# A failing check stops the push.
branch_on_remote=$(remote_sha chore/2-thing)
new_commit
CHECK_EXIT=1
assert_exit 1 push chore/2-thing
CHECK_EXIT=0
assert_exit 0 test "$(remote_sha chore/2-thing)" = "$branch_on_remote"

# So does a missing check.
mv "$fixture/scripts/check" "$fixture/scripts/check.away"
assert_exit 1 push chore/2-thing
mv "$fixture/scripts/check.away" "$fixture/scripts/check"
assert_exit 0 test "$(remote_sha chore/2-thing)" = "$branch_on_remote"

# A new main on a remote that already has branches isn't a new repo's first push.
other_remote="$(tmp_dir)/other.git"
git init -q --bare -b main "$other_remote"
git -C "$fixture" remote add other "$other_remote"
assert_exit 0 git -C "$fixture" push -q other chore/2-thing
assert_exit 1 git -C "$fixture" push -q other main
assert_exit 1 test -n "$(git -C "$other_remote" rev-parse -q --verify refs/heads/main)"
