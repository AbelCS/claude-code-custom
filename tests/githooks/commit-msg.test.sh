#!/bin/sh
# Tests the commit-msg template and dw-lib.sh, installed in a temp repo the way
# setup installs them and run by real commits, so git decides what the hook sees.

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
# shellcheck source=tests/lib/assert.sh
. "$ROOT/tests/lib/assert.sh"

templates="$ROOT/plugins/dev-workflow/skills/setup/templates/githooks"

# The owner's own git settings, such as a comment character, must not change a result.
GIT_CONFIG_GLOBAL=/dev/null
GIT_CONFIG_NOSYSTEM=1
export GIT_CONFIG_GLOBAL GIT_CONFIG_NOSYSTEM

# --- The templates

# Git silently skips a hook that isn't executable.
assert_exit 0 test -x "$templates/commit-msg"
assert_exit 0 test -f "$templates/dw-lib.sh"
for file in commit-msg dw-lib.sh; do
  assert_exit 1 grep -Ewq 'jq|node|python3?' "$templates/$file"
done

# --- The fixture: a path with a space, because git passes hooks that path

repo="$(tmp_dir)/a b/repo"
new_repo "$repo"
hooks="$repo/.githooks"
mkdir -p "$hooks"
cp "$templates/commit-msg" "$templates/dw-lib.sh" "$hooks/"
git -C "$repo" config core.hooksPath .githooks

write_env() {
  cat >"$hooks/dev-workflow.env" <<'ENV'
DW_DEFAULT_BRANCH='main'
DW_CHECK='scripts/check'
DW_CI_ALLOWLIST='.github/workflows/release.yml
.github/workflows/other.yml'
DW_FORMATTERS='*.sh|shfmt -w
*.md|prettier --write'
ENV
}
write_env

message_file="$(tmp_dir)/message"
scratch=$(tmp_dir)

attempt() { # <branch> <message>: a real commit of that message on that branch.
  git -C "$repo" symbolic-ref HEAD "refs/heads/$1" || return 99
  printf '%s\n' "$2" >"$message_file"
  git -C "$repo" commit -q --allow-empty -F "$message_file"
}

accepts() { # <branch> <message>
  assert_exit 0 attempt "$1" "$2"
}

rejects() { # <branch> <message> <text the hook must print>: and it was the hook.
  assert_exit 1 attempt "$1" "$2"
  rejected=$(attempt "$1" "$2" 2>&1)
  assert_contains "$rejected" "commit-msg: "
  assert_contains "$rejected" "$3"
}

on_issue=feat/12-thing
subject='feat: x (#12)'

# --- The format and the issue number

accepts "$on_issue" 'feat(api)!: add thing (#12)'
accepts experiment 'fix: thing'
accepts experiment 'fix: thing (#7)'
accepts "$on_issue" 'fixup! feat: thing'
accepts "$on_issue" 'squash! feat: thing'
accepts "$on_issue" 'amend! feat: x'
accepts "$on_issue" 'fixup! fixup! feat: x'
accepts "$on_issue" 'fix: handle the Claude Code hook input (#12)'
for type in feat fix docs style refactor perf test build ci chore revert; do
  accepts experiment "$type: thing"
done

rejects "$on_issue" 'fix: thing' '#12'
# Another issue's number isn't this branch's, and neither is a longer one.
rejects "$on_issue" 'fix: thing (#13)' '#12'
rejects "$on_issue" 'fix: thing (#123)' '#12'
rejects "$on_issue" 'fix: thing (#12) and more' '#12'
rejects "$on_issue" 'fix: thing(#12)' '#12'
rejects "$on_issue" 'fix: (#12)' '#12'

for bad in \
  'not conventional' \
  "Merge branch 'x'" \
  'nonsense: unknown type' \
  'feat:' \
  'feat: ' \
  'feat(): x' \
  ' feat: x' \
  'fixup! not conventional' \
  'fixup!feat: x' \
  'fixup! ' \
  ''; do
  rejects experiment "$bad" 'expected'
done

# An issue number is only required on a branch whose name carries one.
git -C "$repo" switch -q --detach
assert_exit 0 git -C "$repo" commit -q --allow-empty -m 'fix: thing'

# --- Attribution

robot=$(printf '\360\237\244\226')

while IFS= read -r line; do
  rejects "$on_issue" "$subject

