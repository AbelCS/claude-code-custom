# --- What git removes doesn't count: comments and the diff of `commit -v`

export GIT_EDITOR
editor="$scratch/editor"
cat >"$editor" <<'EDITOR'
#!/bin/sh
cp "$1" "$EDITED"
if [ -n "${TYPED:-}" ]; then cp "$TYPED" "$1"; fi
EDITOR
chmod +x "$editor"
GIT_EDITOR="\"$editor\""
EDITED="$scratch/edited"
export EDITED

change_count=0
stage_a_change() { # The diff holds attribution text that the hook must not read.
  change_count=$((change_count + 1))
  cat >"$repo/notes.txt" <<NOTES
Co-Authored-By: Claude <noreply@anthropic.com>
 Generated with Claude Code
$robot Generated with Claude Code
change $change_count
NOTES
  git -C "$repo" add notes.txt
}

# Commits through the editor, with git's status and the diff in the file it edits.
# <git options...> -- <commit options...>: the message is in $message_file.
edited_commit() {
  git -C "$repo" symbolic-ref HEAD "refs/heads/$on_issue" || return 99
  edited_options=
  while [ "$1" != -- ]; do
    edited_options="$edited_options $1"
    shift
  done
  shift
  # shellcheck disable=SC2086 # Each git option is one word, split on purpose.
  git -C "$repo" $edited_options commit -q --allow-empty -e -F "$message_file" "$@"
}

edited_rejects() { # <text the hook must print> <arguments of edited_commit...>
  edited_expected=$1
  shift
  assert_exit 1 edited_commit "$@"
  edited_output=$(edited_commit "$@" 2>&1)
  assert_contains "$edited_output" "commit-msg: "
  assert_contains "$edited_output" "$edited_expected"
}

printf '%s\n' "$subject" >"$message_file"

# Default comment character. The checks on the edited file show the test is real:
# the hook was given the scissors and the diff.
stage_a_change
assert_exit 0 edited_commit -- -v
edited=$(cat "$EDITED")
assert_contains "$edited" "# ------------------------ >8 ------------------------"
assert_contains "$edited" "+Co-Authored-By: Claude <noreply@anthropic.com>"
assert_exit 0 test "$(git -C "$repo" log -1 --format=%B)" = "$subject"

# Attribution above the scissors still counts.
printf '%s\n\nCo-Authored-By: Claude\n' "$subject" >"$message_file"
stage_a_change
edited_rejects attribution -- -v
git -C "$repo" reset -q

# A comment that only looks like the scissors cuts nothing in git, so nothing here.
printf '%s\n\n# --- >8 ---\nCo-Authored-By: Claude\n' "$subject" >"$message_file"
edited_rejects attribution --

# Comments before the subject and among the trailers.
printf '# A comment first\n\n%s\n\n# Co-Authored-By: Claude\n' "$subject" >"$message_file"
assert_exit 0 edited_commit --
assert_exit 0 test "$(git -C "$repo" log -1 --format=%B)" = "$subject"

# Only comments, no subject.
printf '# %s\n' "$subject" >"$message_file"
edited_rejects expected --

# Git cleans a message from -F before the hook sees it, but not what's typed in the
# editor. It removes trailing space and carriage returns only after the hook, so they
# can't change a verdict.
TYPED="$scratch/typed"
export TYPED
printf '%s  \r\n' "$subject" >"$TYPED"
assert_exit 0 edited_commit --
assert_exit 0 test "$(git -C "$repo" log -1 --format=%B)" = "$subject"
printf '%s\n\nCo-Authored-By: Claude\r\n' "$subject" >"$TYPED"
edited_rejects attribution --
unset TYPED

# Another comment character: its lines and scissors are skipped, and # is text.
printf '; A comment first\n\n%s\n' "$subject" >"$message_file"
stage_a_change
assert_exit 0 edited_commit -c core.commentChar=';' -- -v
assert_contains "$(cat "$EDITED")" "; ------------------------ >8 ------------------------"
assert_exit 0 test "$(git -C "$repo" log -1 --format=%B)" = "$subject"
printf '%s\n\n# Co-Authored-By: Claude\n' "$subject" >"$message_file"
edited_rejects attribution -c core.commentChar=';' --

# A comment string of more than one character.
printf '// A comment first\n\n%s\n' "$subject" >"$message_file"
stage_a_change
assert_exit 0 edited_commit -c core.commentString=// -- -v
assert_contains "$(cat "$EDITED")" "// ------------------------ >8 ------------------------"

# "auto" makes git pick a character no line starts with, so # is ruled out here.
printf '%s\n\n#hashtag\n\nMore text.\n' "$subject" >"$message_file"
stage_a_change
assert_exit 0 edited_commit -c core.commentChar=auto -- -v
assert_contains "$(cat "$EDITED")" "; ------------------------ >8 ------------------------"
# Without scissors the hook can't tell which one, and assumes #.
printf '%s\n' "$subject" >"$message_file"
assert_exit 0 edited_commit -c core.commentChar=auto --

# --- dw-lib.sh

# shellcheck source=plugins/dev-workflow/skills/setup/templates/githooks/dw-lib.sh
. "$templates/dw-lib.sh"

issue_is() { # <branch> <expected>
  assert_exit 0 test "$(dw_issue_from_branch "$1")" = "$2"
}
issue_is feat/12-thing 12
issue_is fix/7-a-longer-slug 7
issue_is chore/30-a/b 30
for no_issue in experiment main feat/12 feat/12- feat/abc-x feature/12-x x/feat/12-y; do
  issue_is "$no_issue" ''
done

# It reads a file as it is: in a pull request body, # starts a heading, not a comment.
body="$scratch/body.md"
printf 'Closes #1\n\n# Co-Authored-By: Claude\n' >"$body"
assert_exit 0 dw_has_attribution "$body"
printf 'Closes #1\n\nClean text about Claude.\n' >"$body"
assert_exit 1 dw_has_attribution "$body"
# A file it can't read isn't a clean file.
assert_exit 2 dw_has_attribution "$scratch/no-such-file"

# Stdin only when no file is named. An empty name is a file it can't read, not a
# reason to read something else, or to wait on stdin.
attributed_stdin() { # [file]
  # shellcheck disable=SC2119 # With no file, it reads stdin.
  printf 'Closes #1\n\nCo-Authored-By: Claude\n' | dw_has_attribution "$@"
}
assert_exit 0 attributed_stdin
assert_exit 2 attributed_stdin ""
assert_exit 2 attributed_stdin "$scratch/no-such-file"
printf 'Clean text about Claude.\n' >"$body"
assert_exit 1 attributed_stdin "$body"

# dw_load_env finds the file next to the script that was run, wherever that runs from.
cat >"$hooks/probe" <<'PROBE'
#!/bin/sh
. "$(dirname "$0")/dw-lib.sh"
dw_load_env || exit 1
printf '%s\n' "$DW_DEFAULT_BRANCH" "$DW_CHECK" "$DW_CI_ALLOWLIST" "$DW_FORMATTERS"
PROBE
chmod +x "$hooks/probe"
expected="main
scripts/check
.github/workflows/release.yml
.github/workflows/other.yml
*.sh|shfmt -w
*.md|prettier --write"
assert_exit 0 test "$(sh "$hooks/probe")" = "$expected"
assert_exit 0 test "$(cd "$hooks" && sh probe)" = "$expected"

# --- A missing or broken env file warns and blocks nothing it doesn't have to

for broken in missing syntax; do
  case $broken in
    missing) rm "$hooks/dev-workflow.env" ;;
    syntax) printf "DW_CHECK='unterminated\n" >"$hooks/dev-workflow.env" ;;
  esac

  assert_exit 1 sh "$hooks/probe"
  assert_contains "$(sh "$hooks/probe" 2>&1)" "dev-workflow.env"

  assert_exit 0 attempt "$on_issue" "$subject"
  warned=$(attempt "$on_issue" "$subject" 2>&1)
  assert_contains "$warned" "dev-workflow.env"
  assert_contains "$warned" "warning"
  rejects "$on_issue" 'not conventional' 'expected'
  rejects "$on_issue" 'fix: thing' '#12'
  rejects "$on_issue" "$subject

Co-Authored-By: Claude" 'attribution'
done

write_env
assert_not_contains "$(attempt "$on_issue" "$subject" 2>&1)" "warning"

# --- A missing library can't check anything, so it blocks, and says why

rm "$hooks/dw-lib.sh"
rejects "$on_issue" "$subject" 'dw-lib.sh is missing'
